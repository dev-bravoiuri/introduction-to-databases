CREATE VIEW vw_relatorio_agendamentos AS
SELECT 
    c.NOME AS NOME_CLIENTE,
    c.TELEFONE,
    a.DATA_AGENDAMENTO,
    s.NOME_SERVICO,
    s.PRECO_SERVICOS
FROM CLIENTES AS c
INNER JOIN AGENDAMENTO AS a 
    ON c.CPF = a.CPF
INNER JOIN SERVICOS AS s 
    ON a.NOME_SERVICO = s.NOME_SERVICO;
    
