SELECT 
    c.NOME,
    c.TELEFONE,
    a.DATA_AGENDAMENTO,
    a.NOME_SERVICO
FROM CLIENTES AS c
INNER JOIN AGENDAMENTO AS a 
    ON c.CPF = a.CPF;
    
    SELECT 
    a.DATA_AGENDAMENTO,
    a.NOME_SERVICO,
    s.PRECO_SERVICOS
FROM AGENDAMENTO AS a
INNER JOIN SERVICOS AS s 
    ON a.NOME_SERVICO = s.NOME_SERVICO;
    
    SELECT 
    c.NOME,
    c.TELEFONE,
    a.DATA_AGENDAMENTO,
    a.NOME_SERVICO
FROM CLIENTES AS c
LEFT JOIN AGENDAMENTO AS a 
    ON c.CPF = a.CPF;
    
    SELECT 
    a.DATA_AGENDAMENTO,
    a.CPF,
    s.NOME_SERVICO,
    s.PRECO_SERVICOS
FROM AGENDAMENTO AS a
RIGHT JOIN SERVICOS AS s 
    ON a.NOME_SERVICO = s.NOME_SERVICO;
    
    SELECT 
    c.NOME AS NOME_CLIENTE,
    c.TELEFONE,
    a.DATA_AGENDAMENTO,
    s.NOME_SERVICO,
    s.PRECO_SERVICOS
FROM CLIENTES AS c
INNER JOIN AGENDAMENTO AS a 
    ON c.CPF = a.CPF
INNER JOIN SERVICOS AS s 
    ON a.NOME_SERVICO = s.NOME_SERVICO;
    
    SELECT 
    c.NOME AS NOME_CLIENTE,
    a.DATA_AGENDAMENTO,
    s.NOME_SERVICO,
    s.PRECO_SERVICOS,
    col.NOME_COLABORADOR
FROM CLIENTES AS c
INNER JOIN AGENDAMENTO AS a 
    ON c.CPF = a.CPF
INNER JOIN SERVICOS AS s 
    ON a.NOME_SERVICO = s.NOME_SERVICO
CROSS JOIN COLABORADORES AS col;

SELECT 
    c.NOME AS NOME_CLIENTE,
    c.TELEFONE,
    a.NOME_SERVICO,
    a.DATA_AGENDAMENTO
FROM CLIENTES AS c
INNER JOIN AGENDAMENTO AS a 
    ON c.CPF = a.CPF
WHERE c.TELEFONE LIKE '66%';

SELECT 
    a.DATA_AGENDAMENTO,
    c.NOME AS NOME_CLIENTE,
    a.NOME_SERVICO
FROM AGENDAMENTO AS a
INNER JOIN CLIENTES AS c 
    ON a.CPF = c.CPF
ORDER BY a.DATA_AGENDAMENTO ASC;

SELECT 
    s.NOME_SERVICO,
    COUNT(a.NOME_SERVICO) AS TOTAL_AGENDAMENTOS,
    SUM(s.PRECO_SERVICOS) AS VALOR_TOTAL_ESTIMADO
FROM SERVICOS AS s
INNER JOIN AGENDAMENTO AS a 
    ON s.NOME_SERVICO = a.NOME_SERVICO
GROUP BY s.NOME_SERVICO;

SELECT 
    c.NOME AS NOME_CLIENTE,
    c.TELEFONE,
    a.DATA_AGENDAMENTO,
    s.NOME_SERVICO,
    s.PRECO_SERVICOS
FROM CLIENTES AS c
