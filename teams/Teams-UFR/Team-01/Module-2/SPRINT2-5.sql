SELECT 
    NOME_SERVICO,
    PRECO_SERVICOS
FROM SERVICOS
WHERE PRECO_SERVICOS > (
    SELECT AVG(PRECO_SERVICOS)
    FROM SERVICOS
);

SELECT 
    NOME,
    TELEFONE
FROM CLIENTES
WHERE CPF IN (
    SELECT CPF
    FROM AGENDAMENTO
);
SELECT 
    NOME_SERVICO,
    PRECO_SERVICOS
FROM SERVICOS
WHERE NOME_SERVICO NOT IN (
    SELECT DISTINCT NOME_SERVICO
    FROM AGENDAMENTO
    WHERE NOME_SERVICO IS NOT NULL
);

SELECT 
    c.NOME,
    c.TELEFONE
FROM CLIENTES AS c
WHERE EXISTS (
    SELECT 1
    FROM AGENDAMENTO AS a
    WHERE a.CPF = c.CPF
);

SELECT 
    c.NOME,
    c.TELEFONE
FROM CLIENTES AS c
WHERE NOT EXISTS (
    SELECT 1
    FROM AGENDAMENTO AS a
    WHERE a.CPF = c.CPF
);

SELECT 
